from typing import List, Optional, Literal
from pydantic import BaseModel, Field, field_validator


class CaseInput(BaseModel):
    """Validation schema for user-submitted civic issue reports."""

    title: str = Field(
        ...,
        min_length=5,
        max_length=200,
        description="Concise summary title of the community issue",
    )
    description: str = Field(
        ...,
        min_length=20,
        max_length=5000,
        description="Detailed factual description of the issue",
    )
    location: str = Field(
        ...,
        min_length=3,
        max_length=250,
        description="Physical location, landmark, or address of the issue",
    )
    category: str = Field(
        ...,
        description="Categorization of the infrastructure or civic issue",
    )
    photo_path: Optional[str] = Field(
        None,
        description="Optional local file path to attached photographic evidence",
    )
    observed_date: Optional[str] = Field(
        None,
        description="Date when the issue was observed (YYYY-MM-DD)",
    )

    @field_validator("title")
    @classmethod
    def clean_title(cls, v: str) -> str:
        cleaned = v.strip()
        if len(cleaned) < 5:
            raise ValueError("Title must be at least 5 characters after trimming.")
        return cleaned

    @field_validator("description")
    @classmethod
    def clean_description(cls, v: str) -> str:
        cleaned = v.strip()
        if len(cleaned) < 20:
            raise ValueError("Description must contain at least 20 characters of detail.")
        return cleaned

    @field_validator("location")
    @classmethod
    def clean_location(cls, v: str) -> str:
        cleaned = v.strip()
        if len(cleaned) < 3:
            raise ValueError("Location must be at least 3 characters.")
        return cleaned


class AIAnalysisResult(BaseModel):
    """Structured AI case analysis generated by NVIDIA Nemotron via Nebius Token Factory."""

    summary: str = Field(
        ...,
        description="Concise 1-2 sentence executive summary of the issue.",
    )
    category: str = Field(
        ...,
        description="Categorized infrastructure/civic problem sector.",
    )
    urgency: Literal["Low", "Medium", "High", "Critical"] = Field(
        ...,
        description="Recommended urgency triage level based on safety, health, and disruption impact.",
    )
    urgency_reasoning: str = Field(
        ...,
        description="Fact-based reasoning justifying the recommended urgency level.",
    )
    distinguished_facts: List[str] = Field(
        default_factory=list,
        description="Key factual observations directly provided in the user's report.",
    )
    assumptions_made: List[str] = Field(
        default_factory=list,
        description="Logical inferences or potential risks assumed from context rather than directly stated.",
    )
    missing_information: List[str] = Field(
        default_factory=list,
        description="Critical missing details that should be gathered (e.g. ward number, exact dimensions).",
    )
    recommended_next_steps: List[str] = Field(
        default_factory=list,
        description="Sequential practical actions for residents or community leaders.",
    )
    responsible_authority_type: str = Field(
        ...,
        description="Institutional jurisdiction (e.g. Municipal Corporation, Roads & Highways, Public Health Department).",
    )
    complaint_letter: str = Field(
        ...,
        description="Formal, professionally phrased complaint letter ready to submit to authorities.",
    )
    evidence_checklist: List[str] = Field(
        default_factory=list,
        description="Specific tangible proof to collect (photos with timestamps, witness statements, GPS tag).",
    )
    follow_up_checklist: List[str] = Field(
        default_factory=list,
        description="Follow-up timeline and escalation protocol (e.g. day 3 reference check, day 7 RTI/escalation).",
    )
    confidence_assessment: str = Field(
        ...,
        description="Explanation of AI confidence level and explicit reminder that urgency is advisory.",
    )


class CaseNote(BaseModel):
    """A progress note or update attached to a case."""

    timestamp: str
    author: str
    content: str


class CaseRecord(BaseModel):
    """Complete case representation stored in database."""

    id: Optional[int] = None
    case_number: str
    title: str
    description: str
    location: str
    category: str
    photo_path: Optional[str] = None
    observed_date: Optional[str] = None
    status: Literal["Open", "In Progress", "Resolved"] = "Open"
    urgency: Literal["Low", "Medium", "High", "Critical"] = "Medium"
    ai_analysis: AIAnalysisResult
    notes: List[CaseNote] = Field(default_factory=list)
    created_at: str
    updated_at: str
    model_used: str
    is_demo: bool = False
